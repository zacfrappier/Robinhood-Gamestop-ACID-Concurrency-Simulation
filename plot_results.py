"""
Create simple SVG graphs from simulation_results.csv.

This uses only the Python standard library so the repo stays easy to run.
"""

from __future__ import annotations

import argparse
import csv
from pathlib import Path
from typing import Dict, List, Tuple


Row = Dict[str, str]


def read_rows(csv_path: Path) -> List[Row]:
    with csv_path.open(newline="", encoding="utf-8") as csv_file:
        return list(csv.DictReader(csv_file))


def group_points(rows: List[Row], metric: str) -> Dict[str, List[Tuple[float, float]]]:
    grouped: Dict[str, List[Tuple[float, float]]] = {}
    for row in rows:
        grouped.setdefault(row["phase"], []).append(
            (float(row["threads"]), float(row[metric]))
        )
    for phase in grouped:
        grouped[phase].sort()
    return grouped


def scale(value: float, src_min: float, src_max: float, dst_min: float, dst_max: float) -> float:
    if src_max == src_min:
        return (dst_min + dst_max) / 2
    ratio = (value - src_min) / (src_max - src_min)
    return dst_min + ratio * (dst_max - dst_min)


def make_line_graph(
    rows: List[Row],
    metric: str,
    title: str,
    y_label: str,
    output_path: Path,
) -> None:
    width = 900
    height = 560
    left = 90
    right = 40
    top = 70
    bottom = 80
    plot_width = width - left - right
    plot_height = height - top - bottom

    grouped = group_points(rows, metric)
    all_x = [point[0] for points in grouped.values() for point in points]
    all_y = [point[1] for points in grouped.values() for point in points]
    x_min, x_max = min(all_x), max(all_x)
    y_min, y_max = 0.0, max(all_y) * 1.1 if all_y else 1.0

    colors = {
        "no_isolation": "#c2410c",
        "strict_isolation": "#1d4ed8",
    }

    def x_pos(x_value: float) -> float:
        return scale(x_value, x_min, x_max, left, left + plot_width)

    def y_pos(y_value: float) -> float:
        return scale(y_value, y_min, y_max, top + plot_height, top)

    lines = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">',
        '<rect width="100%" height="100%" fill="white"/>',
        f'<text x="{width / 2}" y="35" text-anchor="middle" font-family="Arial" font-size="24" font-weight="700">{title}</text>',
        f'<line x1="{left}" y1="{top + plot_height}" x2="{left + plot_width}" y2="{top + plot_height}" stroke="#111827" stroke-width="2"/>',
        f'<line x1="{left}" y1="{top}" x2="{left}" y2="{top + plot_height}" stroke="#111827" stroke-width="2"/>',
        f'<text x="{width / 2}" y="{height - 25}" text-anchor="middle" font-family="Arial" font-size="16">Concurrent Threads</text>',
        f'<text x="25" y="{height / 2}" text-anchor="middle" font-family="Arial" font-size="16" transform="rotate(-90 25 {height / 2})">{y_label}</text>',
    ]

    for tick in sorted(set(all_x)):
        x = x_pos(tick)
        lines.append(f'<line x1="{x:.1f}" y1="{top + plot_height}" x2="{x:.1f}" y2="{top + plot_height + 8}" stroke="#111827"/>')
        lines.append(f'<text x="{x:.1f}" y="{top + plot_height + 30}" text-anchor="middle" font-family="Arial" font-size="13">{int(tick)}</text>')

    for fraction in [0, 0.25, 0.5, 0.75, 1.0]:
        value = y_min + (y_max - y_min) * fraction
        y = y_pos(value)
        lines.append(f'<line x1="{left - 8}" y1="{y:.1f}" x2="{left}" y2="{y:.1f}" stroke="#111827"/>')
        lines.append(f'<line x1="{left}" y1="{y:.1f}" x2="{left + plot_width}" y2="{y:.1f}" stroke="#e5e7eb"/>')
        lines.append(f'<text x="{left - 14}" y="{y + 4:.1f}" text-anchor="end" font-family="Arial" font-size="12">{value:.1f}</text>')

    legend_y = 65
    for index, (phase, points) in enumerate(grouped.items()):
        color = colors.get(phase, "#111827")
        polyline = " ".join(f"{x_pos(x):.1f},{y_pos(y):.1f}" for x, y in points)
        lines.append(f'<polyline points="{polyline}" fill="none" stroke="{color}" stroke-width="3"/>')
        for x, y in points:
            lines.append(f'<circle cx="{x_pos(x):.1f}" cy="{y_pos(y):.1f}" r="5" fill="{color}"/>')
        legend_x = left + index * 190
        lines.append(f'<rect x="{legend_x}" y="{legend_y}" width="18" height="18" fill="{color}"/>')
        lines.append(f'<text x="{legend_x + 26}" y="{legend_y + 14}" font-family="Arial" font-size="14">{phase}</text>')

    lines.append("</svg>")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines), encoding="utf-8")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Plot simulation CSV results as SVG files.")
    parser.add_argument(
        "--input",
        type=Path,
        default=Path("results/simulation_results.csv"),
        help="Input CSV generated by simulation.py.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("results/graphs"),
        help="Directory where SVG graphs will be written.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    rows = read_rows(args.input)
    make_line_graph(
        rows,
        metric="throughput_tx_per_sec",
        title="Throughput by Concurrency Level",
        y_label="Accepted Transactions per Second",
        output_path=args.output_dir / "throughput.svg",
    )
    make_line_graph(
        rows,
        metric="avg_latency_ms",
        title="Average Latency by Concurrency Level",
        y_label="Average Latency (ms)",
        output_path=args.output_dir / "latency.svg",
    )
    make_line_graph(
        rows,
        metric="integrity_violations",
        title="Integrity Violations by Concurrency Level",
        y_label="Integrity Violations",
        output_path=args.output_dir / "integrity_violations.svg",
    )
    print(f"Wrote graphs to: {args.output_dir}")


if __name__ == "__main__":
    main()
